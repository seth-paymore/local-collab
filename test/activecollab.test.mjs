import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const folder = await mkdtemp(join(tmpdir(), 'local-collab-sync-'));
process.env.LOCAL_COLLAB_NOTES = folder;
process.env.LOCAL_COLLAB_CONFIG = join(folder,'no-config.json');
process.env.ACTIVECOLLAB_ACCOUNT_ID = '1000';
process.env.ACTIVECOLLAB_PROJECT_ID = '6';
process.env.ACTIVECOLLAB_USER_ID = '122';
process.env.ACTIVECOLLAB_TOKEN = 'synthetic-test-token';
const notes = await import('../lib/notes.mjs');
const realFetch = globalThis.fetch;
after(async () => { globalThis.fetch = realFetch; await rm(folder, {recursive:true,force:true}); });
let completed = false, changed = false, openSubtask = false, fail = false, assigned = true;
const mutations = [];
const task = (id, number, closed=false) => ({id,task_number:number,project_id:6,name:`Ticket ${number}`,body:'<p>Shared description</p>',task_list_id:570,assignee_ids:assigned?[122]:[100],created_by_id:122,is_completed:closed,completed_on:closed?123:null,updated_on:changed?20:10});
globalThis.fetch = async (url, options={}) => {
  const page = Number(new URL(url).searchParams.get('page') ?? 1);
  const path = new URL(url).pathname.replace('/1000/api/v1','');
  if (options.method !== 'GET') {
    mutations.push({path,options});
    assert.equal(path,'/complete/task/100');
    assert.equal(options.method,'PUT');
    assert.equal(options.body,undefined);
    completed = true;
    return Response.json({});
  }
  if (path==='/users') return Response.json([{id:122,display_name:'Human'}]);
  if (path==='/projects/6/tasks') return Response.json({tasks:[task(100,123,completed)],task_lists:[{id:570,name:'My Tasks'}]});
  if (path==='/projects/6/tasks/archive') return Response.json(page===1 ? Array.from({length:30},(_,i)=>task(200+i,200+i,true)) : [task(101,124,true)]);
  if (path==='/projects/6/tasks/100' || path==='/projects/6/tasks/101') return Response.json({single:path.endsWith('100')?task(100,123,completed):task(101,124,true)});
  if (path.startsWith('/comments/task/')) return fail ? new Response('',{status:503}) : Response.json(Array.from({length:page===1?30:1},(_,i)=>({id:(page-1)*30+i+1,created_by_name:'Developer',created_on:1,body:'Shared comment'})));
  if (path.endsWith('/subtasks')) return Response.json([{id:2,name:'Acceptance requirement',is_completed:!openSubtask}]);
  throw new Error(`Unexpected request: ${path}`);
};

test('full ticket sync and guarded completion keep private notes separate', async () => {
    await notes.addEntry('123',{author:'Human',text:'PRIVATE must never be sent'});
  await notes.addEntry('124',{author:'Human',text:'Archived ticket context'});
  const before = await readFile(join(folder,'ac-123.md'),'utf8');
  let summary = await notes.refreshActiveCollab();
  assert.equal(summary.openTasks,1);
  assert.equal(summary.mine.length,1);
  assert.equal(summary.detailErrors.length,0);
  let note = await notes.getNote('123');
  assert.equal(note.ac.detail.body,'<p>Shared description</p>');
  assert.equal(note.ac.detail.comments[0].body,'Shared comment');
  assert.equal(note.ac.detail.comments.length,31,'comments must include later pages');
  assert.equal(note.ac.detail.subtasks[0].name,'Acceptance requirement');
  assert.equal((await notes.getNote('124')).ac.detail.completed,true);
  assert.equal(await readFile(join(folder,'ac-123.md'),'utf8'),before);
  assert.equal(mutations.length,0);
  await assert.rejects(notes.completeTicket('123',{version:note.ac.detail.version,confirmed:true}),/local working status/);
  await notes.updateMeta('123',{status:'done'});
  await assert.rejects(notes.completeTicket('123',{version:note.ac.detail.version}),/confirm/);
  changed = true;
  await assert.rejects(notes.completeTicket('123',{version:note.ac.detail.version,confirmed:true}),/changed/);
  openSubtask = true;
  let live = await notes.refreshTicket('123');
  await assert.rejects(notes.completeTicket('123',{version:live.version,confirmed:true}),/Open subtasks/);
  openSubtask = false;
  assigned = false;
  live = await notes.refreshTicket('123');
  await assert.rejects(notes.completeTicket('123',{version:live.version,confirmed:true}),/configured user must be assigned/);
  assigned = true;
  live = await notes.refreshTicket('123');
  assert.equal(mutations.length,0);
  const result = await notes.completeTicket('123',{version:live.version,confirmed:true});
  assert.equal(result.completed,true);
  assert.ok(result.completedOn);
  assert.equal(mutations.length,1);
  assert.equal((await notes.activeCollabSummary()).mine.length,0);
  assert.equal((await notes.getNote('123')).ac.completed,true);
  assert.equal((await notes.getNote('123')).entries[0].text,'PRIVATE must never be sent');
  await notes.completeTicket('123',{version:result.version,confirmed:true});
  assert.equal(mutations.length,1,'repeated completion must not mutate again');
  fail = true;
  summary = await notes.refreshActiveCollab();
  assert.equal(summary.detailErrors.length,2);
  note = await notes.getNote('123');
  assert.equal(note.ac.detail.comments[0].body,'Shared comment','last good snapshot retained');
  assert.ok(note.ac.syncError);
  assert.equal(note.entries[0].text,'PRIVATE must never be sent');
});
